import { test, expect } from '@playwright/test'

test('coast to Baguio travels through the road without fading the canvas', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/#worlds')
  await page.getByRole('button', { name: 'Explore at your own pace', exact: true }).click()
  const host = page.locator('.world-canvas')
  await expect(host).toHaveAttribute('data-world', 'coast')
  const select = page.getByRole('group', { name: 'Choose a world' })
  await select.getByRole('button', { name: 'Baguio', exact: true }).click()
  await expect(host).toHaveAttribute('data-world', 'journey')
  await expect.poll(async () => Number(await host.getAttribute('data-journey-progress'))).toBeGreaterThan(.05)
  await expect(host.locator('canvas')).toHaveCSS('opacity', '1')
  await expect(host).toHaveAttribute('data-world', 'mountain', {timeout: 10000})
})

test('reversing a trip mid-corridor keeps the camera on the road', async ({ page }) => {
  await page.goto('/#worlds')
  const host = page.locator('.world-canvas')
  const worlds = page.getByRole('group', { name: 'Choose a world' })
  await expect(host).toHaveAttribute('data-world', 'coast')
  await worlds.getByRole('button', { name: 'Baguio', exact: true }).click()
  await expect.poll(async () => Number(await host.getAttribute('data-journey-progress'))).toBeGreaterThan(.1)
  const before = Number(await host.getAttribute('data-journey-progress'))
  await worlds.getByRole('button', { name: 'La Union', exact: true }).click()
  await expect(host).toHaveAttribute('data-world', 'journey')
  await expect.poll(async () => Number(await host.getAttribute('data-journey-progress'))).toBeLessThan(before)
  await expect(host).toHaveAttribute('data-world', 'coast', { timeout: 10000 })
})

test('rapid destination changes settle on the latest world and its selection works', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/#worlds')
  await page.getByRole('button', { name: 'Explore at your own pace', exact: true }).click()
  const host = page.locator('.world-canvas')
  await expect(host).toHaveAttribute('data-world', 'coast')
  const worlds = page.getByRole('group', { name: 'Choose a world' })
  await worlds.getByRole('button', { name: 'Baguio', exact: true }).click()
  await worlds.getByRole('button', { name: 'Their little space', exact: true }).click()
  await expect(host).toHaveAttribute('data-world', 'little-space')
  await page.getByRole('button', { name: 'Open the memory book', exact: true }).click()
  await expect(page.locator('.world-discovery')).toBeVisible()
  await expect.poll(async () => Number(await host.locator('canvas').evaluate(el => getComputedStyle(el).opacity))).toBe(1)
  await page.waitForTimeout(1200)
  await expect(host).toHaveAttribute('data-world', 'little-space')
})

test('reduced motion changes destination immediately', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#worlds')
  await page.getByRole('button', { name: 'Explore at your own pace', exact: true }).click()
  const host = page.locator('.world-canvas')
  await expect(host).toHaveAttribute('data-world', 'coast')
  await page.getByRole('group', { name: 'Choose a world' }).getByRole('button', { name: 'Baguio', exact: true }).click()
  await expect(host).toHaveAttribute('data-world', 'mountain')
  await expect(host.locator('canvas')).toHaveCSS('opacity', '1')
  await page.getByRole('button', { name: 'Open the reminder book', exact: true }).click()
  await expect(page.locator('.world-discovery')).toBeVisible()
})
