import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
async function seek(page:Page,progress:number){
 await page.locator('.narrative-track').evaluate((el,p)=>{const top=el.getBoundingClientRect().top+scrollY;const distance=el.clientHeight-innerHeight+78;window.scrollTo({top:top-78+distance*p,behavior:'instant'})},progress)
 await expect.poll(async()=>Number(await page.locator('.narrative-track').getAttribute('data-progress'))).toBeCloseTo(progress,2)
}
test('scroll story changes real camera poses, visits four worlds, opens gift and reverses',async({page})=>{
 await page.emulateMedia({reducedMotion:'no-preference'})
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',e=>{if(e.type()==='error')errors.push(e.text())})
 await page.goto('/')
 await page.getByRole('button',{name:'Follow the story',exact:true}).click()
 await expect(page.locator('.world-canvas canvas')).toBeVisible()
 const canvas=page.locator('.world-canvas')
 await seek(page,.05);const before=await canvas.getAttribute('data-camera')
 await seek(page,.16);await expect(canvas).not.toHaveAttribute('data-camera',before!)
 for(const [progress,world,title] of [[.08,'coast','Two places. One us.'],[.35,'journey','And there you are.'],[.6,'mountain','A little light between us.'],[.8,'little-space','Closer, one little step.']] as const){
  await seek(page,progress);await expect(canvas).toHaveAttribute('data-world',world)
  await expect(page.locator('.narrative-copy h3')).toHaveText(title)
  await expect(page.locator('.narrative-sticky')).toHaveCSS('position','sticky')
  await page.locator('.narrative-sticky').screenshot({path:`test-results/story-${world}.png`})
 }
 await seek(page,.05);const apart=Number(await canvas.getAttribute('data-lovers-distance'))
 await seek(page,.999);await expect(page.locator('.narrative-letter')).toBeVisible()
 expect(Number(await canvas.getAttribute('data-lovers-distance'))).toBeLessThan(apart)
 await expect(page.locator('.narrative-letter')).toContainText('I love you')
 await page.getByRole('button',{name:'Read my full letter'}).click()
 await expect(page.getByRole('dialog')).toContainText('I love you. This is for you.')
 await page.keyboard.press('Escape')
 await expect(page.getByRole('button',{name:'Read my full letter'})).toBeFocused()
 await expect.poll(async()=>Number(await canvas.getAttribute('data-connection-progress'))).toBe(1)
 await seek(page,.1);await expect.poll(async()=>Number(await canvas.getAttribute('data-connection-progress'))).toBe(0)
 await seek(page,.1);await expect(canvas).toHaveAttribute('data-world','coast')
 await seek(page,.8)
 await page.getByRole('button',{name:'Explore freely',exact:true}).click()
 await expect(canvas).toHaveAttribute('data-world','little-space')
 await expect.poll(async()=>JSON.parse((await canvas.getAttribute('data-targets'))!).map((target:{id:string})=>target.id)).toContain('gift')
 await expect(page.getByRole('group',{name:'Choose a world',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Baguio',exact:true}).click()
 await expect(canvas).toHaveAttribute('data-world','mountain')
 expect(errors).toEqual([])
})
test('mobile story chapter links, reduced motion, skip and fallback retain readable content',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await page.getByRole('button',{name:'Follow the story',exact:true}).click()
 await expect(page.locator('.world-canvas canvas')).toBeVisible()
 await seek(page,.6)
 await expect(page.locator('.narrative-copy h3')).toContainText('light')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.locator('.narrative-sticky').screenshot({path:'test-results/story-mobile.png'})
 expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()).violations).toEqual([])
 await page.getByRole('navigation',{name:'Story chapters'}).getByRole('button',{name:'Together',exact:true}).click()
 await expect(page.locator('.world-canvas')).toHaveAttribute('data-world','little-space')
 await seek(page,.999);await expect(page.locator('.narrative-letter')).toBeVisible()
 await page.getByRole('link',{name:'Skip the journey',exact:true}).click()
 await expect(page).toHaveURL(/#about$/)
})


test('short viewports keep story copy and controls reachable',async({page})=>{
 for(const viewport of [{width:1280,height:600},{width:390,height:500}]){
  await page.setViewportSize(viewport)
  await page.goto('/')
  await page.getByRole('button',{name:'Follow the story',exact:true}).click()
  await seek(page,.999)
  const copy=page.locator('.narrative-copy')
  await expect(copy).toHaveCSS('overflow-y','auto')
  const bounds=await copy.evaluate(el=>{const r=el.getBoundingClientRect();return {top:r.top,bottom:r.bottom,height:innerHeight}})
  expect(bounds.top).toBeGreaterThanOrEqual(0)
  expect(bounds.bottom).toBeLessThanOrEqual(bounds.height)
  await page.getByRole('button',{name:'Read my full letter'}).scrollIntoViewIfNeeded()
  await page.getByRole('button',{name:'Read my full letter'}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('navigation',{name:'Story chapters'})).toBeInViewport()
 }
})
