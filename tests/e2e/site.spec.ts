import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('home, navigation, reminders, and replayable letter', async ({ page }) => {
 await page.goto('/')
 await expect(page.locator('#home h1')).toContainText('Welcome home')
 await page.getByRole('button', { name: 'Gentle reminders', exact: true }).click()
 const first = await page.locator('.reminder-stage h3').textContent()
 await page.getByRole('button', { name: 'Another reminder' }).click()
 await expect(page.locator('.reminder-stage h3')).not.toHaveText(first!)
 await page.locator('#home').getByRole('button', { name: 'A little surprise', exact: true }).click()
 await page.getByRole('button', { name: 'Open your letter' }).click()
 await expect(page.locator('.letter-paper')).toBeVisible()
 await page.getByRole('button', { name: 'Replay surprise' }).click()
 await expect(page.getByRole('button', { name: 'Open your letter' })).toBeVisible()
 await page.getByRole('button', { name: 'Open your letter' }).click()
 await expect(page.locator('.letter-paper')).toBeVisible()
})

test('local memory create, edit, export, delete, import and invalid backup', async ({ page }) => {
 await page.goto('/#memories')
 await page.getByRole('button', { name: 'Add a memory', exact: true }).first().click()
 await page.getByLabel('Title', { exact: true }).fill('A quiet afternoon')
 await page.getByLabel('Date', { exact: true }).fill('2026-10-10')
 await page.getByLabel('Story', { exact: true }).fill('Test memory, not personal content.')
 await page.getByRole('button', { name: 'Save memory', exact: true }).click()
 await expect(page.getByRole('heading', { name: 'A quiet afternoon' })).toBeVisible()
 await page.getByRole('button', { name: 'Edit A quiet afternoon' }).click()
 await page.getByLabel('Title', { exact: true }).fill('A slower afternoon')
 await page.getByRole('button', { name: 'Save memory', exact: true }).click()
 await page.reload()
 await expect(page.getByRole('heading', { name: 'A slower afternoon' })).toBeVisible()
 const downloadPromise = page.waitForEvent('download')
 await page.getByRole('button', { name: 'Export backup' }).click()
 const download = await downloadPromise
 const path = await download.path()
 await page.getByRole('button', { name: 'Delete A slower afternoon' }).click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await page.getByRole('button', { name: 'Delete memory', exact: true }).click()
 await expect(page.getByRole('heading', { name: 'A slower afternoon' })).toHaveCount(0)
 await page.getByLabel('Import backup file').setInputFiles(path!)
 await expect(page.getByRole('heading', { name: 'A slower afternoon' })).toBeVisible()
 await page.getByLabel('Import backup file').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{bad') })
 await expect(page.getByRole('alert')).toContainText('valid JSON')
 await expect(page.getByRole('heading', { name: 'A slower afternoon' })).toBeVisible()
})

test('mobile navigation, keyboard dialog, reduced motion, layout and accessibility', async ({ page }) => {
 await page.setViewportSize({ width: 375, height: 812 })
 await page.emulateMedia({ reducedMotion: 'reduce' })
 await page.goto('/')
 await page.getByRole('button', { name: 'Open navigation' }).click()
 await page.getByRole('button', { name: 'About her', exact: true }).click()
 await expect(page.getByRole('heading', { name: 'A little about you', exact: true })).toBeVisible()
 await expect(page.getByRole('button', { name: 'Open navigation' })).toBeVisible()
 for (const route of ['home','about','reminders','memories','surprise']) {
  await page.goto('/#'+route)
  expect(await page.locator(`#${route}`).count()).toBeGreaterThan(0)
  const widthCheck = await page.evaluate(() => ({scrollWidth:document.documentElement.scrollWidth, innerWidth, offenders:[...document.querySelectorAll('body *')].map(el=>({tag:el.tagName,cls:typeof el.className==='string'?el.className:'',id:el.id,right:Math.round(el.getBoundingClientRect().right),left:Math.round(el.getBoundingClientRect().left)})).filter(x=>x.right>innerWidth+1||x.left< -1).slice(0,8)}))
  expect(widthCheck.scrollWidth <= widthCheck.innerWidth, JSON.stringify(widthCheck)).toBe(true)
  const result = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()
  expect(result.violations).toEqual([])
 }
 await page.goto('/#memories')
 await page.getByRole('button', { name: 'Add a memory', exact: true }).first().click()
 await page.keyboard.press('Escape')
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await expect(page.getByRole('button', { name: 'Add a memory', exact: true }).first()).toBeFocused()
})
